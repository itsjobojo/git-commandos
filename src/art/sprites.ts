import { PALETTE } from './palette';

const spriteCache = new Map<string, OffscreenCanvas>();

function createSprite(pixels: number[][]): OffscreenCanvas {
  const h = pixels.length;
  const w = pixels[0].length;
  const canvas = new OffscreenCanvas(w, h);
  const ctx = canvas.getContext('2d')!;

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const idx = pixels[y][x];
      if (idx > 0) {
        ctx.fillStyle = PALETTE[idx];
        ctx.fillRect(x, y, 1, 1);
      }
    }
  }

  return canvas;
}

function getOrCreate(name: string, pixels: number[][]): OffscreenCanvas {
  let sprite = spriteCache.get(name);
  if (!sprite) {
    sprite = createSprite(pixels);
    spriteCache.set(name, sprite);
  }
  return sprite;
}

